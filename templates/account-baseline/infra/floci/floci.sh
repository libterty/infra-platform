#!/usr/bin/env bash
# Run account-baseline end to end against Floci, a local AWS emulator, without touching a real account.
# The template is never modified: it is copied outside the repo, each stack gets a provider override and a backend
# file that point at Floci, and the copy's own stacks.sh runs in ORDER. See README.md for what this proves and what not.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
template_tf="$(cd "${here}/../terraform" && pwd)"

FLOCI_IMAGE="${FLOCI_IMAGE:-docker.io/floci/floci:2.4.0}"
FLOCI_CONTAINER="${FLOCI_CONTAINER:-floci-account-baseline}"
FLOCI_PORT="${FLOCI_PORT:-4566}"
# Outside the repo: validate.sh scans every .tf under templates/.
tmp_root="${TMPDIR:-/tmp}"
WORK_DIR="${FLOCI_WORK_DIR:-${tmp_root%/}/floci-account-baseline}"
ENV_NAME=dev
REGION=ap-northeast-1
ACCOUNT_ID=111111111111
PROJECT=baseline
STATE_BUCKET=baseline-dev-tfstate-floci
# localhost, not 127.0.0.1: S3 Control prefixes the account ID to the host, and <account>.localhost still resolves
# to loopback while <account>.127.0.0.1 does not.
endpoint="http://localhost:${FLOCI_PORT}"
work_tf="${WORK_DIR}/terraform"

usage() {
  cat >&2 <<'USAGE'
用法：floci.sh <run|up|prepare|init|apply|verify|destroy|down>

  run      up → prepare → init → apply → verify → destroy，一次跑完（預設）
  up       啟動 Floci container（已在跑就沿用）
  prepare  把 account-baseline 複製到 FLOCI_WORK_DIR，換上指向 Floci 的 provider 與 backend，建 state bucket
  init     複本的 stacks.sh dev all init
  apply    依 ORDER apply 全部
  verify   每個 stack 再 plan 一次要沒有變更，並檢查 SSM 參數與帳號層的設定
  destroy  依 ORDER 反向 destroy
  down     移除 Floci container
USAGE
}

die() {
  echo "錯誤：$*" >&2
  exit 2
}

log() { echo "== $*"; }

runtime() {
  if command -v docker >/dev/null 2>&1; then
    echo docker
  elif command -v podman >/dev/null 2>&1; then
    echo podman
  else
    die "找不到 docker 或 podman"
  fi
}

# Every AWS call from here goes to Floci with fake keys; a real profile in the caller's shell is dropped.
floci_env() {
  unset AWS_PROFILE AWS_DEFAULT_PROFILE AWS_SESSION_TOKEN AWS_SECURITY_TOKEN AWS_VAULT AWS_ROLE_ARN \
    AWS_WEB_IDENTITY_TOKEN_FILE AWS_CONFIG_FILE AWS_SHARED_CREDENTIALS_FILE
  export AWS_ENDPOINT_URL="$endpoint"
  export AWS_ACCESS_KEY_ID="$ACCOUNT_ID"
  export AWS_SECRET_ACCESS_KEY=floci
  export AWS_REGION="$REGION"
  export AWS_DEFAULT_REGION="$REGION"
  export AWS_PAGER=""
}

awsl() { aws --endpoint-url "$endpoint" "$@"; }

stacks() { "${work_tf}/stacks.sh" "$ENV_NAME" "$@"; }

require_work() {
  [ -x "${work_tf}/stacks.sh" ] || die "還沒 prepare：找不到 ${work_tf}/stacks.sh"
}

# No container runtime socket: nothing in this template runs a container (no Lambda, ECS or ECR).
cmd_up() {
  local rt
  rt="$(runtime)"
  if [ "$("$rt" ps -q --filter "name=^${FLOCI_CONTAINER}$")" != "" ]; then
    log "Floci 已在跑：${FLOCI_CONTAINER}"
  else
    "$rt" rm -f "$FLOCI_CONTAINER" >/dev/null 2>&1 || true
    log "啟動 ${FLOCI_IMAGE}"
    "$rt" run -d --name "$FLOCI_CONTAINER" \
      -p "127.0.0.1:${FLOCI_PORT}:4566" \
      -e FLOCI_DEFAULT_ACCOUNT_ID="$ACCOUNT_ID" \
      "$FLOCI_IMAGE" >/dev/null
  fi
  floci_env
  local _
  for _ in $(seq 1 30); do
    if awsl sts get-caller-identity --query Account --output text 2>/dev/null | grep -qx "$ACCOUNT_ID"; then
      log "Floci 就緒，帳號 ${ACCOUNT_ID}"
      return 0
    fi
    sleep 1
  done
  die "Floci 30 秒內沒有回應：${endpoint}"
}

# The backend file keeps each stack's real state key; only the location and credentials change.
write_backend() {
  local stack="$1" key
  key="$(sed -n 's/^key *= *"\(.*\)"$/\1/p' "${template_tf}/${stack}/envs/${ENV_NAME}.tfbackend")"
  [ -n "$key" ] || die "${stack}/envs/${ENV_NAME}.tfbackend 沒有 key"
  cat >"${work_tf}/${stack}/envs/${ENV_NAME}.tfbackend" <<EOF
# Generated by floci.sh for the local emulator; the template's own file is untouched.
bucket                      = "${STATE_BUCKET}"
key                         = "${key}"
region                      = "${REGION}"
use_lockfile                = true
use_path_style              = true
endpoints                   = { s3 = "${endpoint}" }
access_key                  = "${ACCOUNT_ID}"
secret_key                  = "floci"
skip_credentials_validation = true
skip_requesting_account_id  = true
skip_metadata_api_check     = true
skip_region_validation      = true
EOF
}

# Second-plan diffs that come from Floci's responses, checked against the API on Floci 2.4.0; any other diff fails.
# Format: <stack>|<resource address>|<reason>
KNOWN_DRIFT=(
  "audit|module.config_recorder.aws_config_configuration_recorder.this|DescribeConfigurationRecorders 不回 recordingStrategy"
)

# Resources Floci can create but not delete: destroy drops them from state instead, and down discards Floci's copy.
# Format: <stack>|<resource address>|<reason>
UNDELETABLE=(
  "detect|module.securityhub.aws_securityhub_account.this|不支援 DisableSecurityHub（DELETE /accounts）"
  "detect|module.inspector.aws_inspector2_enabler.this|不支援 Inspector2 Disable（POST /disable）"
)

order() {
  # The same line check-ssm-contract.sh parses.
  sed -n 's/^ORDER=(\(.*\))$/\1/p' "${template_tf}/stacks.sh"
}

# Floci 2.4.0 answers ModifyInstanceMetadataDefaults with UnsupportedOperation, so the copy, and only the copy, turns
# the IMDSv2 account default off. README.md lists it as not covered.
patch_imdsv2_default() {
  local f="${work_tf}/defaults/security.tf"
  local from='imdsv2_default            = true'
  [ "$(grep -cF "$from" "$f")" -eq 1 ] || die "defaults/security.tf 的 imdsv2_default 寫法變了，floci.sh 要跟著改"
  FROM="$from" perl -0pi -e 's/\Q$ENV{FROM}\E/imdsv2_default            = false/' "$f"
  echo "  defaults/security.tf：imdsv2_default 改成 false（Floci 不支援 ModifyInstanceMetadataDefaults）"
}

cmd_prepare() {
  floci_env
  log "複製 account-baseline 到 ${WORK_DIR}"
  rm -rf "$work_tf"
  mkdir -p "$WORK_DIR"
  rsync -a --exclude '.terraform/' --exclude '.terraform-*/' "${template_tf}/" "${work_tf}/"
  local s
  for s in $(order); do
    cp "${here}/provider_override.tf.tmpl" "${work_tf}/${s}/floci_override.tf"
    write_backend "$s"
  done
  patch_imdsv2_default
  if ! awsl s3api head-bucket --bucket "$STATE_BUCKET" >/dev/null 2>&1; then
    log "建立 state bucket ${STATE_BUCKET}"
    awsl s3api create-bucket --bucket "$STATE_BUCKET" \
      --create-bucket-configuration "LocationConstraint=${REGION}" >/dev/null
  fi
}

cmd_init() {
  require_work
  floci_env
  stacks all init
}

cmd_apply() {
  require_work
  floci_env
  stacks all apply --yes
}

# only_known_drift <stack> <plan log>: true when every resource the plan changes is listed in KNOWN_DRIFT.
only_known_drift() {
  local stack="$1" planlog="$2" addr entry known
  while IFS= read -r addr; do
    known=0
    for entry in ${KNOWN_DRIFT[@]+"${KNOWN_DRIFT[@]}"}; do
      if [ "${entry%%|*}" = "$stack" ] && [ "$(echo "$entry" | cut -d'|' -f2)" = "$addr" ]; then
        known=1
        echo "    ${addr}：$(echo "$entry" | cut -d'|' -f3-)"
      fi
    done
    [ "$known" -eq 1 ] || return 1
  done < <(sed 's/\x1b\[[0-9;]*m//g' "$planlog" | sed -n 's/^  # \(.*\) will be .*$/\1/p; s/^  # \(.*\) must be .*$/\1/p')
}

# expect <label> <want> <command...>: run a read-only AWS call against Floci and compare its text output.
expect() {
  local label="$1" want="$2" got
  shift 2
  got="$("$@" 2>&1 | tr '\t\n' '  ' | sed 's/ *$//')" || true
  echo "  ${label} → ${got}（要 ${want}）"
  [ "$got" = "$want" ]
}

prefix="${PROJECT}-${ENV_NAME}"

check_account_settings() {
  local failed=0 vault
  expect "trail 在記錄" True awsl cloudtrail get-trail-status --name "${prefix}-trail" --query IsLogging \
    --output text || failed=1
  expect "Config recorder 在記錄" True awsl configservice describe-configuration-recorder-status \
    --query 'ConfigurationRecordersStatus[0].recording' --output text || failed=1
  expect "GuardDuty detector 數" 1 awsl guardduty list-detectors --query 'length(DetectorIds)' --output text ||
    failed=1
  expect "Security Hub 已啟用" True awsl securityhub describe-hub --query 'HubArn != null' --output text ||
    failed=1
  expect "S3 帳號層 public access block" "True True True True" awsl s3control get-public-access-block \
    --account-id "$ACCOUNT_ID" --query 'PublicAccessBlockConfiguration.[BlockPublicAcls,IgnorePublicAcls,BlockPublicPolicy,RestrictPublicBuckets]' \
    --output text || failed=1
  expect "密碼政策最短長度" 14 awsl iam get-account-password-policy --query PasswordPolicy.MinimumPasswordLength \
    --output text || failed=1
  expect "EBS 預設加密" True awsl ec2 get-ebs-encryption-by-default --query EbsEncryptionByDefault --output text ||
    failed=1
  vault="$(awsl backup list-backup-vaults --query "BackupVaultList[?starts_with(BackupVaultName, '${prefix}')].BackupVaultName | [0]" --output text)"
  expect "Backup vault ${vault} 已 lock" True awsl backup describe-backup-vault --backup-vault-name "$vault" \
    --query Locked --output text || failed=1
  expect "Budget 數" 1 awsl budgets describe-budgets --account-id "$ACCOUNT_ID" --query 'length(Budgets)' \
    --output text || failed=1
  return "$failed"
}

cmd_verify() {
  require_work
  floci_env
  local failed=0 s rc
  log "每個 stack 再 plan 一次：要沒有變更"
  for s in $(order); do
    rc=0
    stacks "$s" plan -- -detailed-exitcode -input=false >"${WORK_DIR}/plan-${s}.log" 2>&1 || rc=$?
    case "$rc" in
      0) echo "  ${s}: 沒有變更" ;;
      2)
        if only_known_drift "$s" "${WORK_DIR}/plan-${s}.log"; then
          echo "  ${s}: 只有已知的 Floci 差異"
        else
          echo "  ${s}: 有變更（${WORK_DIR}/plan-${s}.log）"
          failed=1
        fi
        ;;
      *)
        echo "  ${s}: plan 失敗（${WORK_DIR}/plan-${s}.log）"
        failed=1
        ;;
    esac
  done

  log "SSM 參數（跨 stack 契約）"
  awsl ssm get-parameters-by-path --path "/${PROJECT}/${ENV_NAME}" --recursive --query 'Parameters[].Name' \
    --output text | tr '\t' '\n' | sort | sed 's/^/  /'

  log "帳號層的設定"
  check_account_settings || failed=1

  if [ "$failed" -eq 0 ]; then log "verify 全部通過"; else log "verify 有項目沒通過"; fi
  return "$failed"
}

forget_undeletable() {
  local entry stack addr
  for entry in "${UNDELETABLE[@]}"; do
    stack="${entry%%|*}"
    addr="$(echo "$entry" | cut -d'|' -f2)"
    if (cd "${work_tf}/${stack}" && TF_DATA_DIR=".terraform-${ENV_NAME}" terraform state list "$addr" 2>/dev/null |
      grep -qxF "$addr"); then
      echo "  ${stack}：${addr} 從 state 移除，不 destroy（$(echo "$entry" | cut -d'|' -f3-)）"
      (cd "${work_tf}/${stack}" && TF_DATA_DIR=".terraform-${ENV_NAME}" terraform state rm "$addr" >/dev/null)
    fi
  done
}

cmd_destroy() {
  require_work
  floci_env
  forget_undeletable
  stacks all destroy --yes
}

cmd_down() {
  "$(runtime)" rm -f "$FLOCI_CONTAINER" >/dev/null 2>&1 || true
  log "已移除 ${FLOCI_CONTAINER}"
}

cmd_run() {
  cmd_up
  cmd_prepare
  cmd_init
  cmd_apply
  local rc=0
  cmd_verify || rc=$?
  cmd_destroy
  return "$rc"
}

action="${1:-run}"
case "$action" in
  run | up | prepare | init | apply | verify | destroy | down) "cmd_${action}" ;;
  -h | --help | help) usage ;;
  *)
    usage
    exit 2
    ;;
esac
